// Package inventory renders the discovered-facts file — the exact YAML shape
// tools/bmc-inventory.sh writes to control/inventory/<node>.yaml, so `pk-metal
// inventory` output diffs cleanly against the existing fact files.
// The printer is hand-rolled: the format is printf-shaped (flow-style list items,
// conditional annotations), not what a YAML marshaller emits.
package inventory

import (
	"context"
	"fmt"
	"io"
	"slices"
	"strconv"
	"strings"
	"time"

	"github.com/dennisklein/platform-kit/metal/internal/bmc"
)

// Facts is everything the fact file carries, gathered over one bmc.Client.
type Facts struct {
	Manager bmc.Manager
	Chassis bmc.Chassis
	Media   []bmc.VirtualMedia
	Systems []bmc.System
}

// Gather reads all fact-file inputs (read-only GETs).
func Gather(ctx context.Context, c bmc.Client) (Facts, error) {
	var f Facts
	var err error
	if f.Manager, err = c.Manager(ctx); err != nil {
		return f, err
	}
	if f.Chassis, err = c.Chassis(ctx); err != nil {
		return f, err
	}
	if f.Media, err = c.Media(ctx); err != nil {
		return f, err
	}
	// gofish walks collections concurrently — order EVERY list (fact files are diffed).
	slices.SortFunc(f.Media, func(a, b bmc.VirtualMedia) int { return strings.Compare(a.ID, b.ID) })
	slices.SortFunc(f.Chassis.Adapters, func(a, b bmc.Adapter) int { return strings.Compare(a.Model, b.Model) })
	if f.Systems, err = c.Systems(ctx); err != nil {
		return f, err
	}
	if len(f.Systems) == 0 {
		return f, fmt.Errorf("inventory: endpoint exposes no systems")
	}
	for i := range f.Systems {
		sys := &f.Systems[i]
		slices.SortFunc(sys.NICs, func(a, b bmc.NIC) int { return strings.Compare(a.ID, b.ID) })
		slices.SortFunc(sys.Drives, func(a, b bmc.Drive) int { return strings.Compare(a.Serial, b.Serial) })
	}
	return f, nil
}

// Write renders the fact file. node and address come from the caller (ledger name and
// reachable address — the endpoint knows neither); ts pins the header for testability.
func Write(w io.Writer, node, address string, ts time.Time, f Facts) {
	sys := f.Systems[0]

	fmt.Fprintf(w, "# GENERATED by pk-metal inventory (%s) — re-run to refresh; do not hand-edit.\n",
		ts.UTC().Format(time.RFC3339))
	fmt.Fprintf(w, "node: %s\n", node)
	fmt.Fprintf(w, "bmc:\n")
	fmt.Fprintf(w, "  address: %s\n", q(address))
	fmt.Fprintf(w, "  mac: %s\n", q(orQ(f.Manager.MAC)))
	fmt.Fprintf(w, "  firmware: %s\n", q(orQ(f.Manager.FirmwareVersion)))
	fmt.Fprintf(w, "  hostname: %s # iBMC reports the chassis serial here\n", q(orQ(f.Manager.Hostname)))
	fmt.Fprintf(w, "  virtualmedia:\n")
	for _, m := range f.Media {
		fmt.Fprintf(w, "    - { id: %s, media_types: [%s], insert_standard: %t, oem_actions: [%s] }\n",
			q(m.ID), quoteList(m.MediaTypes), m.InsertStandard, quoteList(m.OemActions))
	}
	fmt.Fprintf(w, "system:\n")
	fmt.Fprintf(w, "  manufacturer: %s\n", q(orQ(sys.Manufacturer)))
	fmt.Fprintf(w, "  model: %s\n", q(orQ(sys.Model)))
	if f.Chassis.Model != "" && f.Chassis.Model != sys.Model {
		fmt.Fprintf(w, "  board: %s # chassis Model — the real platform\n", q(f.Chassis.Model))
	}
	if sys.SerialNumber != "" {
		fmt.Fprintf(w, "  serial: %s\n", q(sys.SerialNumber))
	} else {
		fmt.Fprintf(w, "  serial: %s # chassis board serial — Systems/1 exposes none\n", q(orQ(f.Chassis.BoardSerial)))
	}
	fmt.Fprintf(w, "  uuid: %s\n", q(orQ(sys.UUID)))
	fmt.Fprintf(w, "  power: %s\n", q(string(sys.PowerState)))
	fmt.Fprintf(w, "  memory_gib: %d\n", sys.MemoryGiB)
	fmt.Fprintf(w, "  cpu: { model: %s, count: %d }\n", q(orQ(sys.CPUModel)), sys.CPUCount)
	fmt.Fprintf(w, "nics: # system/LOM view\n")
	for _, n := range sys.NICs {
		fmt.Fprintf(w, "  - { id: %s, mac: %s }\n", q(n.ID), q(orQ(n.MAC)))
	}
	if len(f.Chassis.Adapters) > 0 {
		fmt.Fprintf(w, "adapters: # PCIe NICs (chassis NetworkAdapters view)\n")
		for _, a := range f.Chassis.Adapters {
			fmt.Fprintf(w, "  - { model: %s, port_macs: [%s] }\n", q(a.Model), quoteList(a.PortMACs))
		}
	}
	if len(sys.Drives) > 0 {
		fmt.Fprintf(w, "drives:\n")
		for _, d := range sys.Drives {
			fmt.Fprintf(w, "  - { model: %s, serial: %s, capacity_gib: %d, media: %s, protocol: %s }\n",
				q(d.Model), q(d.Serial), d.CapacityGiB, q(orQ(d.MediaType)), q(orQ(d.Protocol)))
		}
	}
}

func orQ(s string) string {
	if s == "" {
		return "?"
	}
	return s
}

func quoteList(items []string) string {
	if len(items) == 0 {
		return ""
	}
	quoted := make([]string, len(items))
	for i, s := range items {
		quoted[i] = q(s)
	}
	return strings.Join(quoted, ",")
}

// q double-quotes s for YAML. Go's %q escapes agree with YAML's on valid
// UTF-8, but it writes a byte that is not UTF-8 as \xNN, which YAML reads
// back as the code point U+00NN: a different, plausible value. YAML text is
// Unicode and cannot carry such bytes, so they become U+FFFD instead.
func q(s string) string {
	return strconv.Quote(strings.ToValidUTF8(s, "\uFFFD"))
}
