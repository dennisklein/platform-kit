#!/usr/bin/env bash
# Writes config/crd/kustomization.yaml from the CRD files that are there.
# kustomize has no globs, and a hand-kept list is the file somebody forgets when
# a kind is added: the new CRD would be generated, committed and never deployed.
# Runs as part of `mise run generate`, so the list cannot drift from the types.
set -euo pipefail

SCRIPT=${0##*/}

die() {
  echo "Error: $*" >&2
  exit 1
}

crd_dir=${1:-}
[[ -n $crd_dir && -d $crd_dir ]] \
  || die "usage: $SCRIPT <crd-directory>, e.g.: $SCRIPT config/crd"

# controller-gen names every CRD <group>_<plural>.yaml, which is what keeps this
# glob from picking up the kustomization it is about to write.
shopt -s nullglob
crds=("$crd_dir"/*_*.yaml)
(( ${#crds[@]} )) \
  || die "no CRDs in $crd_dir. Generate them first: mise run generate"

{
  echo "# Generated by \`mise run generate\` from the files in this directory. Do not edit."
  echo "apiVersion: kustomize.config.k8s.io/v1beta1"
  echo "kind: Kustomization"
  echo "resources:"
  for crd in "${crds[@]}"; do
    echo "  - ${crd##*/}"
  done
} > "$crd_dir/kustomization.yaml"
